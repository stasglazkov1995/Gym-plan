// ---------- Render ----------
function renderFood(){
  let html='';
  for(const [k,d] of Object.entries(FOOD)){
    const g='food-'+k;
    const muscles=d.gym&&PLAN[k]?' · '+PLAN[k].main.map(x=>GROUPS[x].n.toLowerCase()).join(' + '):'';
    html+=`<section class="day mode-food" id="d-${g}"><div class="dayhead"><h2>${d.title}</h2><span class="daytag${d.gym?'':' off'}">${d.tag}${muscles}</span><div class="prog" id="prog-${g}" data-lbl="food"></div></div>`;
    d.meals.forEach((ml,i)=>{
      const key=g+'-'+i;
      html+=`<div class="ex meal" data-k="${key}" data-g="${g}" data-n="1">
        <div class="name"><span class="num">${i+1}</span>${ml.n}</div>
        <ul class="items">${ml.i.map(([a,b])=>`<li><span>${a}</span><b>${b}</b></li>`).join('')}</ul>
        ${chk(key,'food')}</div>`;
    });
    html+=`</section>`;
  }
  html+=`<div class="tips mode-food"><h3>Примітка</h3><p>Крупи та макарони зважувати сухими, м'ясо й рибу — сирими. Калорійність орієнтовна й залежить від брендів та способу приготування.</p></div>`;
  return html;
}
